//! EIP-2935 block hash history contract constants.

use alloy_primitives::keccak256;

use crate::evm;

/// EIP-2935 block hash history contract address.
pub const BLOCK_HASH_HISTORY_ADDRESS: evm::Address = evm::Address::new([
    0x00, 0x00, 0xf9, 0x08, 0x27, 0xf1, 0xc5, 0x3a, 0x10, 0xcb, 0x7a, 0x02, 0x33, 0x5b, 0x17, 0x53,
    0x20, 0x00, 0x29, 0x35,
]);

/// Prague EIP-2935 block hash history runtime bytecode.
pub const BLOCK_HASH_HISTORY_CODE: &[u8] = &[
    0x33, 0x73, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xfe, 0x14, 0x60, 0x46, 0x57, 0x60, 0x20, 0x36, 0x03, 0x60, 0x42,
    0x57, 0x5f, 0x35, 0x60, 0x01, 0x43, 0x03, 0x81, 0x11, 0x60, 0x42, 0x57, 0x61, 0x1f, 0xff, 0x81,
    0x43, 0x03, 0x11, 0x60, 0x42, 0x57, 0x61, 0x1f, 0xff, 0x90, 0x06, 0x54, 0x5f, 0x52, 0x60, 0x20,
    0x5f, 0xf3, 0x5b, 0x5f, 0x5f, 0xfd, 0x5b, 0x5f, 0x35, 0x61, 0x1f, 0xff, 0x60, 0x01, 0x43, 0x03,
    0x06, 0x55, 0x00,
];

/// Returns the Keccak-256 code hash for [`BLOCK_HASH_HISTORY_CODE`].
pub fn block_hash_history_code_hash() -> evm::Hash {
    let digest = keccak256(BLOCK_HASH_HISTORY_CODE);
    let mut hash = [0u8; evm::HASH_LENGTH];
    hash.copy_from_slice(digest.as_slice());
    evm::Hash::new(hash)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn constants_match_eip2935() {
        assert_eq!(
            BLOCK_HASH_HISTORY_ADDRESS.to_hex_string(),
            "0000f90827f1c53a10cb7a02335b175320002935"
        );
        assert_eq!(BLOCK_HASH_HISTORY_CODE.len(), 83);
        assert_eq!(
            block_hash_history_code_hash(),
            evm::Hash::new(keccak256(BLOCK_HASH_HISTORY_CODE).0)
        );
    }
}
