use core::{mem, ptr::NonNull};

use crate::{
    abi::{Declaration, Definitions},
    compat::types::CLTyped,
    linkme::distributed_slice,
    schema::{Schema, SchemaMessage, SchemaType},
    serializers::AbiConvention,
};

#[derive(Debug)]
pub struct AbiType {
    pub name: &'static str,
    pub cl_type: Box<dyn CLTyped>,
}

#[derive(Debug)]
pub struct AbiParam {
    pub name: &'static str,
    pub decl: AbiType,
}

#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub struct AbiLocation {
    pub file: &'static str,
    pub line: u32,
    pub col: u32,
}

#[derive(Debug, Copy, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum AbiKind {
    /// struct SmartContract {}
    SmartContract,
    TraitImpl {
        trait_name: &'static str,
        impl_name: &'static str,
    },
    Function,
}

#[derive(Debug)]
pub enum AbiItem {
    /// impl Foo { fn method(params) -> result_decl }
    EntryPoint {
        name: &'static str,
        params: &'static [AbiParam],
        abi_convention: Option<AbiConvention>,
        result_decl: AbiType,
        kind: AbiKind,
        location: AbiLocation,
        fptr: fn() -> (),
    },
}

#[distributed_slice]
#[linkme(crate = crate::linkme)]
pub static ABI_ITEMS: [AbiItem] = [..];

#[derive(Debug, Clone)]
pub struct Message {
    pub name: &'static str,
    pub decl: &'static str,
}

#[distributed_slice]
#[linkme(crate = crate::linkme)]
pub static MESSAGES: [Message] = [..];

#[distributed_slice]
#[linkme(crate = crate::linkme)]
pub static NAMED_KEYS: [NamedKey] = [..];

#[derive(Debug, Clone)]
pub struct NamedKey {
    pub name: &'static str,
    pub decl: fn() -> Declaration,
}

/// All of the entry points generated by proc macro will be registered here.
#[distributed_slice]
#[linkme(crate = crate::linkme)]
pub static ENTRYPOINTS: [fn() -> crate::schema::SchemaEntryPoint] = [..];

#[distributed_slice]
#[linkme(crate = crate::linkme)]
pub static ABI_COLLECTORS: [fn(&mut crate::abi::Definitions)] = [..];

pub fn casper_collect_schema() -> Schema {
    // Collect definitions
    let definitions = {
        let mut definitions = Definitions::default();

        for abi_collector in ABI_COLLECTORS {
            abi_collector(&mut definitions);
        }

        definitions
    };

    // Collect messages
    let messages = {
        let mut messages = Vec::new();

        for message in MESSAGES {
            messages.push(SchemaMessage {
                name: message.name.to_owned(),
                decl: message.decl.to_owned(),
            });
        }

        messages
    };

    // Collect named keys
    let named_keys = {
        let mut named_keys = Vec::new();

        for named_key in NAMED_KEYS {
            named_keys.push(crate::schema::SchemaStableKey {
                name: named_key.name.to_owned(),
                decl: (named_key.decl)(),
            });
        }

        named_keys
    };

    // Collect entrypoints
    let entry_points = {
        let mut entry_points = Vec::new();
        for entrypoint in ENTRYPOINTS {
            entry_points.push(entrypoint());
        }
        entry_points
    };

    // Construct a schema object from the extracted information
    Schema {
        name: "contract".to_string(),
        version: None,
        type_: SchemaType::Contract {
            state: "Contract".to_string(),
        },
        definitions,
        entry_points,
        messages,
        named_keys,
    }
}

/// This function is called by the host to collect the schema from the contract.
///
/// This is considered internal implementation detail and should not be used directly.
/// Primary user of this API is `cargo-casper` tool that will use it to extract schema from the
/// contract.
///
/// # Safety
/// Pointer to json bytes passed to the callback is valid only within the scope of that function.
#[export_name = "__cargo_casper_collect_schema"]
pub unsafe extern "C" fn cargo_casper_collect_schema(size_ptr: *mut u64) -> *mut u8 {
    let schema = casper_collect_schema();
    // Write the schema using the provided writer
    let mut json_bytes = serde_json::to_vec(&schema).expect("Serialized schema");
    NonNull::new(size_ptr)
        .expect("expected non-null ptr")
        .write(json_bytes.len().try_into().expect("usize to u64"));
    let ptr = json_bytes.as_mut_ptr();
    mem::forget(json_bytes);
    ptr
}
